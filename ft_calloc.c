#include "libft.h"

void	*ft_calloc(int count, int size)
{
	unsigned char	*tmp;

	tmp = malloc(size * count);
	if (!tmp)
		return (NULL);
	ft_memset(tmp, 0, size * count);
	return (tmp);
}
